// NPCs and the first quest, as data. Dialogue is chosen by quest stage; effects are interpreted by the quest system.

export interface Effect {
  give?: { id: string; qty: number }[];
  take?: { id: string; qty: number }[];
  xp?: { skill: SkillId; amount: number }[];
  stage?: number;
  flag?: string;
  /** a quest key, slotted on your keyring */
  key?: string;
  /** something seen, not said: shown like a page you're reading (a Lock's memory, a letter); `react` lines join in
   * when their flags are set, then `after` closes it */
  vision?: { title: string; sub: string; lines: string[]; react?: React[]; after?: string[] };
  /** someone signs on to your crew */
  crew?: string;
  /** a moment begins that you answer with the timing tap (data/active.ts MOMENTS) */
  moment?: 'line';
}

/** Lines that are only said when the world is a certain way: who you befriended, beat, recruited or lost. */
export interface React { flags: string[]; not?: string[]; lines: string[] }

export interface DialogueNode {
  lines: string[];
  /** reactive lines, said after `lines` when their flags are (and `not` flags aren't) set; then `after` */
  react?: React[];
  after?: string[];
  requires?: { id: string; qty: number }; // only offered when the player carries this
  /** only offered once these flags are set (other quests done); `missing` is said until then */
  needsFlags?: string[];
  missing?: string[]; // said instead when requirement not met
  effect?: Effect;
}

export interface NpcDef {
  id: string;
  name: string;
  title: string;
  idle: string[];
  shop?: boolean; // keeps a shop (see SHOPS: the shop's keeper)
  bank?: boolean; // talking opens your bank
  heals?: string; // restores you to full health, with this line
  /** leaves this spot once the flag is set (a Tide who joined your crew isn't standing on the shore any more) */
  goneWhen?: string;
  /** ...and back again once this flag is set (someone taken, then rescued) */
  backWhen?: string;
  ferry?: { to: 'bellwether' | 'sunreach' | 'amberhold' | 'wrack' | 'lockhaven' | 'saltglass' | 'longstrand'; price: number }[]; // offers passage to other harbours
}

